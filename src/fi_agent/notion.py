"""Publish the report to a Notion database.

One database row per trading day, titled e.g. "Watchlist · 2026-10-09". The first run of
the day that has something to report creates the row; later runs that day replace its
body in place, so the page URL stays stable and the database is not flooded with one row
per watch cycle. The trading day is taken in New York time, not UTC, so an evening run
still lands on the session it describes.

Credentials never appear in configuration or in this file. The integration token and the
database link are read from NOTION_TOKEN and NOTION_PARENT_PAGE, which in practice come
from the gitignored .env. The token is never logged.

Like email, publishing failures are reported but never raised: Notion being unreachable
must not cost you the report that was already written to disk.
"""

from __future__ import annotations

import logging
import os
import re
import time
from collections.abc import Iterator
from dataclasses import dataclass
from datetime import date, datetime
from typing import Any

import httpx
from dotenv import load_dotenv

from fi_agent.config import NotionSettings, project_root
from fi_agent.data.market import MARKET_TZ
from fi_agent.report.render import build_view

log = logging.getLogger(__name__)

TOKEN_ENV = "NOTION_TOKEN"
DATABASE_ENV = "NOTION_PARENT_PAGE"

API_URL = "https://api.notion.com/v1"
API_VERSION = "2022-06-28"

# Hard limits of the Notion API: characters per rich text item, and blocks per children
# array in a single request.
TEXT_LIMIT = 2000
CHILDREN_LIMIT = 100
MAX_RETRIES = 3

ICON = {"type": "emoji", "emoji": "📈"}
CONFIDENCE_COLOR = {"high": "green", "medium": "yellow", "low": "red"}
DISCLAIMER = (
    "Prices and percentages are computed from market data, not generated by the language "
    "model. Narrative text is model-written and may be wrong. This is a news monitoring "
    "tool, not investment advice."
)

Block = dict[str, Any]
RichText = list[dict[str, Any]]


class NotionError(Exception):
    """The API answered with an error status."""


@dataclass
class Credentials:
    token: str
    database_id: str


@dataclass
class PublishResult:
    published: bool
    detail: str
    url: str | None = None


# --------------------------------------------------------------------------------------
# Credentials
# --------------------------------------------------------------------------------------


def database_id_from(value: str) -> str | None:
    """Extract the database id from a bare id, a dashed UUID or a full Notion URL.

    A database URL looks like notion.so/<workspace>/<Title>-<id>?v=<view id>. Only the
    last path segment is searched, and only its trailing 32 hex characters taken, so
    neither the view id nor a title ending in hex-like letters ("...Code") is mistaken
    for the database.
    """
    path = value.strip().split("?", 1)[0].split("#", 1)[0].rstrip("/")
    segment = path.rsplit("/", 1)[-1].replace("-", "").lower()
    match = re.search(r"[0-9a-f]{32}$", segment)
    return match.group(0) if match else None


def load_credentials() -> tuple[Credentials | None, str]:
    """Read the token and database from the environment, loading .env first if present.

    Returns the credentials, or None with the reason they are unusable.
    """
    load_dotenv(project_root() / ".env", override=False)
    token = os.environ.get(TOKEN_ENV, "").strip()
    target = os.environ.get(DATABASE_ENV, "").strip()
    if not token:
        return None, f"{TOKEN_ENV} is not set"
    if not target:
        return None, f"{DATABASE_ENV} is not set"
    database_id = database_id_from(target)
    if database_id is None:
        return None, f"{DATABASE_ENV} does not contain a Notion database id"
    return Credentials(token, database_id), ""


