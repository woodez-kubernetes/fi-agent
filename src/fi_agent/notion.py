def make_client(token: str, transport: httpx.BaseTransport | None = None) -> httpx.Client:
    return httpx.Client(
        base_url=API_URL,
        headers={
            "Authorization": f"Bearer {token}",
            "Notion-Version": API_VERSION,
            "Content-Type": "application/json",
        },
        timeout=30,
        transport=transport,
    )


def _request(
    client: httpx.Client, method: str, path: str, body: dict[str, Any] | None = None
) -> dict[str, Any]:
    """One API call, retrying rate limits and server errors.

    Notion allows about three requests a second; clearing and rewriting a page can burst
    past that, and the documented response is to wait for Retry-After.
    """
    for attempt in range(MAX_RETRIES + 1):
        response = client.request(method, path, json=body)
        retryable = response.status_code == 429 or response.status_code >= 500
        if retryable and attempt < MAX_RETRIES:
            try:
                delay = float(response.headers.get("Retry-After", ""))
            except ValueError:
                delay = 1.0 + attempt
            time.sleep(delay)
            continue
        if response.is_error:
            try:
                payload = response.json()
            except ValueError:
                payload = {}
            raise NotionError(
                f"{method} {path} returned {response.status_code} "
                f"{payload.get('code', '')}: {payload.get('message', '')}".strip()
            )
        return response.json()
    raise NotionError(f"{method} {path} still failing after {MAX_RETRIES} retries")


# --------------------------------------------------------------------------------------
# Block construction
# --------------------------------------------------------------------------------------


def text(
    content: str | None,
    *,
    bold: bool = False,
    italic: bool = False,
    code: bool = False,
    color: str = "default",
    link: str | None = None,
) -> RichText:
    """Rich text runs for one styled string, split to respect the per-item limit."""
    if not content:
        return []
    # A malformed link makes Notion reject the whole request, so only plain web URLs
    # from feeds are linked.
    url = link if link and link.startswith(("http://", "https://")) else None
    if url and len(url) > TEXT_LIMIT:
        url = None
    annotations = {
        "bold": bold,
        "italic": italic,
        "strikethrough": False,
        "underline": False,
        "code": code,
        "color": color,
    }
    return [
        {
            "type": "text",
            "text": {"content": content[i : i + TEXT_LIMIT], "link": {"url": url} if url else None},
            "annotations": annotations,
        }
        for i in range(0, len(content), TEXT_LIMIT)
    ]


def _block(kind: str, rich_text: RichText, **extra: Any) -> Block:
    return {"object": "block", "type": kind, kind: {"rich_text": rich_text, **extra}}


def paragraph(rich_text: RichText) -> Block:
    return _block("paragraph", rich_text)


def heading(level: int, rich_text: RichText, children: list[Block] | None = None) -> Block:
    """A heading; given children it becomes a toggle heading that folds them away."""
    if children is None:
        return _block(f"heading_{level}", rich_text)
    return _block(f"heading_{level}", rich_text, is_toggleable=True, children=children)


def bullet(rich_text: RichText) -> Block:
    return _block("bulleted_list_item", rich_text)


def quote(rich_text: RichText) -> Block:
    return _block("quote", rich_text)


def callout(emoji: str, rich_text: RichText, color: str = "gray_background") -> Block:
    return _block("callout", rich_text, icon={"type": "emoji", "emoji": emoji}, color=color)


def divider() -> Block:
    return {"object": "block", "type": "divider", "divider": {}}


def table(header: list[str], rows: list[list[RichText]]) -> Block:
    def row(cells: list[RichText]) -> Block:
        return {"object": "block", "type": "table_row", "table_row": {"cells": cells}}

    # The header row counts toward the per-request children limit.
    body = rows[: CHILDREN_LIMIT - 1]
    return {
        "object": "block",
        "type": "table",
        "table": {
            "table_width": len(header),
            "has_column_header": True,
            "has_row_header": False,
            "children": [row([text(h, bold=True) for h in header])] + [row(r) for r in body],
        },
    }


def _pct(value: float, *, bold: bool = False) -> RichText:
    return text(f"{value:+.2f}%", bold=bold, color="green" if value >= 0 else "red")


def _dash() -> RichText:
    return text("—", color="gray")


def _ticker_cell(symbol: str, name: str) -> RichText:
    return text(symbol, bold=True) + text(f"  {name}", color="gray")


def _volume_cell(ratio: float | None) -> RichText:
    return text(f"{ratio:.1f}×") if ratio else _dash()


def _mover_row(finding: Any) -> list[RichText]:
    mover = finding.mover
    quote_ = mover.quote
    sector = (
        text(f"{mover.sector_etf} ") + _pct(mover.sector_pct)
        if mover.sector_etf and mover.sector_pct is not None
        else _dash()
    )
    driver = (
        text(finding.analysis.driver.replace("_", " "))
        if finding.analysis
        else text("no analysis", italic=True, color="gray")
    )
    return [
        _ticker_cell(mover.symbol, mover.name),
        text(f"{quote_.price:,.2f}"),
        _pct(quote_.pct_change, bold=True),
        _pct(mover.residual_pct) if mover.residual_pct is not None else _dash(),
        sector,
        _volume_cell(quote_.volume_ratio),
        driver,
    ]


def _quiet_row(mover: Any) -> list[RichText]:
    return [
        _ticker_cell(mover.symbol, mover.name),
        text(f"{mover.quote.price:,.2f}"),
        _pct(mover.quote.pct_change),
        _pct(mover.residual_pct) if mover.residual_pct is not None else _dash(),
        _volume_cell(mover.quote.volume_ratio),
    ]


def _citation(claim: str, article: Any) -> RichText:
    meta = f", {article.source}" if article.source else ""
    if article.published_at:
        meta += f", {article.published_at.strftime('%d %b %H:%M UTC')}"
    runs = text(claim) + text("\n— ", color="gray") + text(article.title, link=article.url)
    runs += text(meta, color="gray")
    if not article.text:
        runs += text(" (headline only)", italic=True, color="gray")
    return runs


def _finding_section(finding: Any) -> Block:
    """A toggle heading per mover, folding the analysis and its sources beneath it."""
    mover = finding.mover
    quote_ = mover.quote
    title = text(f"{mover.symbol} — {mover.name}  ") + _pct(quote_.pct_change, bold=True)
    title += text(f"  {quote_.price:,.2f} {quote_.currency}", color="gray")

    children: list[Block] = []
    analysis = finding.analysis
    if analysis:
        children.append(paragraph(text(analysis.headline, bold=True)))
        tags = text(analysis.driver.replace("_", " "), code=True) + text("  ")
        tags += text(
            f"{analysis.confidence} confidence",
            code=True,
            color=CONFIDENCE_COLOR.get(analysis.confidence, "default"),
        )
        if finding.dropped_claims:
            tags += text("  ") + text(
                f"{len(finding.dropped_claims)} claim(s) struck", code=True, color="orange"
            )
        children.append(paragraph(tags))
        children.append(paragraph(text(analysis.narrative)))
        if finding.cited:
            children.extend(bullet(_citation(claim, article)) for claim, article in finding.cited)
        else:
            children.append(
                paragraph(
                    text("No citation survived verification for this move.", italic=True)
                )
            )
        if analysis.watch_next:
            children.append(
                callout(
                    "🔎",
                    text("What would confirm this: ", bold=True) + text(analysis.watch_next),
                    color="blue_background",
                )
            )
    else:
        reason = f" — {finding.degraded_reason}" if finding.degraded_reason else ""
        children.append(
            paragraph(text(f"Narrative analysis unavailable{reason}.", italic=True, color="gray"))
        )
        children.extend(
            bullet(
                text(article.title, link=article.url) + text(f" — {article.source}", color="gray")
            )
            for article in finding.articles[:4]
        )

    if mover.triggers:
        children.append(
            paragraph(text("Triggers: " + " · ".join(mover.triggers), color="gray"))
        )
    return heading(3, title, children=children)


def build_blocks(view: dict[str, Any]) -> list[Block]:
    """The page body for a rendered view, mirroring the HTML report's structure."""
    context = view["context"]
    findings = view["findings"]
    quiet = view["quiet"]
    summary = view["summary"]
    diagnostics = view["diagnostics"]
    errors = view["errors"]
    updated = view["generated_at"].astimezone(MARKET_TZ)
    total = len(findings) + len(quiet)

    header = text(f"{context.benchmark} ") + _pct(context.benchmark_pct, bold=True)
    header += text(
        f"  ·  {len(findings)} of {total} names flagged  ·  "
        f"market {'open' if view['market_open'] else 'closed'}"
    )
    header += text(f"\nUpdated {updated:%H:%M} ET", color="gray")
    blocks: list[Block] = [callout("📊", header)]

    if errors:
        blocks.append(
            callout(
                "⚠️",
                text(f"{len(errors)} issue(s) during this run: ", bold=True)
                + text("; ".join(errors)),
                color="red_background",
            )
        )

    if summary.summary:
        blocks.append(heading(2, text("Summary")))
        blocks.append(quote(text(summary.summary)))
        if summary.themes:
            themes = text("Themes  ", color="gray")
            for theme in summary.themes:
                themes += text(theme, code=True) + text("  ")
            blocks.append(paragraph(themes))

    blocks.append(heading(2, text("Movers")))
    if findings:
        blocks.append(
            table(
                ["Ticker", "Last", "Change", f"Vs {context.benchmark}", "Sector", "Volume",
                 "Driver"],
                [_mover_row(f) for f in findings],
            )
        )
        blocks.append(heading(2, text("What moved and why")))
        blocks.extend(_finding_section(f) for f in findings)
    else:
        blocks.append(
            paragraph(text("No watchlist name cleared the screening thresholds this run."))
        )

    if quiet:
        blocks.append(heading(2, text("Rest of the watchlist")))
        blocks.append(
            table(
                ["Ticker", "Last", "Change", f"Vs {context.benchmark}", "Volume"],
                [_quiet_row(m) for m in quiet],
            )
        )

    footer = text(f"Run {view['run_id']} · {diagnostics.duration_s}s · model ", color="gray")
    footer += text(diagnostics.model, code=True)
    footer += text(
        f" · {diagnostics.llm_calls} LLM calls ({diagnostics.llm_seconds}s)", color="gray"
    )
    if diagnostics.degraded:
        footer += text(f" · degraded: {', '.join(diagnostics.degraded)}", color="gray")
    blocks += [divider(), paragraph(footer), paragraph(text(DISCLAIMER, italic=True, color="gray"))]
    return blocks


