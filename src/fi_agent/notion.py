# Page lifecycle
# --------------------------------------------------------------------------------------


def trading_day(moment: datetime) -> date:
    return moment.astimezone(MARKET_TZ).date()


def _title_property(schema: dict[str, Any]) -> str:
    for name, prop in schema.items():
        if prop.get("type") == "title":
            return name
    raise NotionError("database has no title property")


def page_properties(
    schema: dict[str, Any], settings: NotionSettings, title: str, day: date, model: str
) -> dict[str, Any]:
    """Row properties, setting only the configured columns the database actually has.

    The database may be shared with other tools and carry columns that mean nothing for
    a multi-ticker report; those are left alone rather than guessed at.
    """

    def has(name: str, *kinds: str) -> bool:
        return bool(name) and schema.get(name, {}).get("type") in kinds

    properties: dict[str, Any] = {_title_property(schema): {"title": text(title)}}
    if has(settings.date_property, "date"):
        properties[settings.date_property] = {"date": {"start": day.isoformat()}}
    if has(settings.model_property, "rich_text"):
        properties[settings.model_property] = {"rich_text": text(model)}
    if settings.category and has(settings.category_property, "multi_select"):
        properties[settings.category_property] = {"multi_select": [{"name": settings.category}]}
    elif settings.category and has(settings.category_property, "select"):
        properties[settings.category_property] = {"select": {"name": settings.category}}
    return properties


def find_page(
    client: httpx.Client, database_id: str, title_property: str, title: str
) -> dict[str, Any] | None:
    result = _request(
        client,
        "POST",
        f"/databases/{database_id}/query",
        {"filter": {"property": title_property, "title": {"equals": title}}, "page_size": 1},
    )
    pages = result.get("results", [])
    return pages[0] if pages else None


def _chunks(blocks: list[Block]) -> Iterator[list[Block]]:
    for i in range(0, len(blocks), CHILDREN_LIMIT):
        yield blocks[i : i + CHILDREN_LIMIT]


def append_blocks(client: httpx.Client, block_id: str, blocks: list[Block]) -> None:
    for chunk in _chunks(blocks):
        _request(client, "PATCH", f"/blocks/{block_id}/children", {"children": chunk})


def clear_page(client: httpx.Client, page_id: str) -> None:
    """Delete a page's top-level blocks; nested blocks go with their parents.

    Every id is collected before anything is deleted, so pagination cursors are not
    invalidated mid-walk.
    """
    ids: list[str] = []
    cursor: str | None = None
    while True:
        path = f"/blocks/{page_id}/children?page_size=100"
        if cursor:
            path += f"&start_cursor={cursor}"
        result = _request(client, "GET", path)
        ids.extend(block["id"] for block in result.get("results", []))
        cursor = result.get("next_cursor")
        if not result.get("has_more") or not cursor:
            break
    for block_id in ids:
        _request(client, "DELETE", f"/blocks/{block_id}")


def publish(
    settings: NotionSettings,
    credentials: Credentials,
    state: dict[str, Any],
    client: httpx.Client | None = None,
) -> PublishResult:
    """Create or refresh the row for the run's trading day. Never raises.

    `state` holds the same arguments `build_view` takes, as returned by
    `publish.load_state`.
    """
    view = build_view(**state)
    day = trading_day(view["generated_at"])
    title = f"{settings.title_prefix} · {day.isoformat()}"
    blocks = build_blocks(view)
    database_id = credentials.database_id

    owns_client = client is None
    http = client or make_client(credentials.token)
    try:
        schema = _request(http, "GET", f"/databases/{database_id}")["properties"]
        properties = page_properties(schema, settings, title, day, view["diagnostics"].model)
        existing = find_page(http, database_id, _title_property(schema), title)
        if existing:
            page_id, url = existing["id"], existing.get("url")
            # Should the rewrite fail after this, the page is left partly filled until
            # the next run replaces it; the report on disk is unaffected either way.
            clear_page(http, page_id)
            _request(http, "PATCH", f"/pages/{page_id}", {"properties": properties, "icon": ICON})
            append_blocks(http, page_id, blocks)
            action = "updated"
        else:
            page = _request(
                http,
                "POST",
                "/pages",
                {
                    "parent": {"database_id": database_id},
                    "icon": ICON,
                    "properties": properties,
                    "children": blocks[:CHILDREN_LIMIT],
                },
            )
            url = page.get("url")
            append_blocks(http, page["id"], blocks[CHILDREN_LIMIT:])
            action = "created"
    except (httpx.HTTPError, NotionError, KeyError) as exc:
        return PublishResult(False, f"{type(exc).__name__}: {exc}")
    finally:
        if owns_client:
            http.close()

    log.info("notion page %s: %s", action, url)
    return PublishResult(True, f"{action} '{title}'", url)


def maybe_publish(
    settings: NotionSettings, state: dict[str, Any], flagged: list[str]
) -> PublishResult:
    """Publish if enabled and, unless configured otherwise, only when something flagged."""
    if not settings.enabled:
        return PublishResult(False, "notion disabled")
    if settings.only_when_flagged and not flagged:
        return PublishResult(False, "nothing flagged")
    credentials, problem = load_credentials()
    if credentials is None:
        return PublishResult(False, problem)
    result = publish(settings, credentials, state)
    if not result.published:
        log.warning("notion not updated: %s", result.detail)
    return result


def check(credentials: Credentials, client: httpx.Client | None = None) -> tuple[bool, str]:
    """Read-only reachability check for `doctor`. Writes nothing."""
    owns_client = client is None
    http = client or make_client(credentials.token)
    try:
        database = _request(http, "GET", f"/databases/{credentials.database_id}")
    except NotionError as exc:
        if "object_not_found" in str(exc):
            return False, "database not found; share it with the integration (••• → Connections)"
        return False, str(exc)
    except httpx.HTTPError as exc:
        return False, f"{type(exc).__name__}: {exc}"
    finally:
        if owns_client:
            http.close()
    name = "".join(t.get("plain_text", "") for t in database.get("title", []))
    return True, f"database '{name}' reachable"
